const assert = require("assert");
const engine = require("../pre-race-prediction.js");
const fields = ["runningStyle","cornerPosition","previousFinish","previousCorner","closingRank","distanceRecord","goingRecord","courseRecord"];
const values = ["先行",3,2,4,2,"普通","良","東京"];
const makeHorse = (number, filled) => { const horse = {number:String(number),name:"品質テスト"+number,jockey:"テスト騎手",trainer:"テスト厩舎"}; fields.slice(0,filled).forEach((field,index) => {horse[field]=values[index]}); return horse; };
const predict = horses => engine.generatePreRacePrediction({date:"2026-06-14",course:"東京競馬場",raceNumber:"1R",raceName:"品質テスト",horses});
const high = predict([makeHorse(1,8),makeHorse(2,8),makeHorse(3,8)]);
assert.strictEqual(high.dataQuality.rate,100);
assert.strictEqual(high.dataQuality.rank,"高");
const medium = predict([makeHorse(1,6),makeHorse(2,6),makeHorse(3,6)]);
assert.strictEqual(medium.dataQuality.rate,75);
assert.strictEqual(medium.dataQuality.rank,"中");
const low = predict([makeHorse(1,0),makeHorse(2,0),makeHorse(3,0)]);
assert.strictEqual(low.dataQuality.rate,0);
assert.strictEqual(low.dataQuality.rank,"低");
const mixed = predict([makeHorse(1,8),makeHorse(2,6),makeHorse(3,0)]);
assert.strictEqual(mixed.dataQuality.filled,14);
assert.strictEqual(mixed.dataQuality.total,24);
assert.strictEqual(mixed.dataQuality.rate,58);
assert.deepStrictEqual(mixed.dataQuality.perHorse.map(h => h.rate),[100,75,0]);
assert.ok(mixed.markdown.includes("データ充足率: 58%"));
assert.ok(mixed.markdown.includes("データ品質: 中"));
console.log("dataQuality.test.js passed");
